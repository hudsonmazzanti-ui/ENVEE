// Regenerates src/theme/assets.ts from the images in assets/art, assets/catalog, assets/line and assets/stickers.
//   node scripts/gen-assets.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// Stickers are named by ASIN, so they get a prefix to make a valid, unclashing key: st_<ASIN>.
const dirs = ['assets/art', 'assets/catalog', 'assets/line', 'assets/stickers'];
const prefix = { 'assets/stickers': 'st_' };
const lines = [];
for (const dir of dirs) {
  if (!fs.existsSync(path.join(root, dir))) continue;
  const files = fs
    .readdirSync(path.join(root, dir))
    .filter((f) => /\.(png|jpe?g|webp|svg)$/.test(f))
    .sort();
  for (const f of files) {
    const key = (prefix[dir] ?? '') + f.replace(/\.[^.]+$/, '').replace(/[^a-zA-Z0-9]/g, '_');
    lines.push(`  ${key}: require('../../${dir}/${f}'),`);
  }
}

const out = `// AUTO-GENERATED by scripts/gen-assets.mjs from assets/art, assets/catalog, assets/line and assets/stickers. Do not edit by hand.
// art: generated placeholder product illustrations. catalog: cut-outs of real product photos.
// stickers (st_<ASIN>): cut-outs of cached Amazon products, made by scripts/stickers (npm run stickers).
// line: the app's line art (rooms, empty states), rendered by scripts/build-line-art.mjs.
import type { ImageSourcePropType } from 'react-native';

export const art = {
${lines.join('\n')}
} satisfies Record<string, ImageSourcePropType>;

export type ArtKey = keyof typeof art;

export const fonts = {
  Cinzel_400Regular: require('@expo-google-fonts/cinzel/400Regular/Cinzel_400Regular.ttf'),
  Cinzel_500Medium: require('@expo-google-fonts/cinzel/500Medium/Cinzel_500Medium.ttf'),
  Cinzel_600SemiBold: require('@expo-google-fonts/cinzel/600SemiBold/Cinzel_600SemiBold.ttf'),
  Jost_400Regular: require('@expo-google-fonts/jost/400Regular/Jost_400Regular.ttf'),
  Jost_500Medium: require('@expo-google-fonts/jost/500Medium/Jost_500Medium.ttf'),
  Jost_600SemiBold: require('@expo-google-fonts/jost/600SemiBold/Jost_600SemiBold.ttf'),
  // Icon fonts, preloaded so icons never flash in and so the inlined web build needs no asset URLs.
  feather: require('@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts/Feather.ttf'),
  ionicons: require('@expo/vector-icons/build/vendor/react-native-vector-icons/Fonts/Ionicons.ttf'),
};
`;
fs.writeFileSync(path.join(root, 'src/theme/assets.ts'), out);
console.log(`src/theme/assets.ts: ${lines.length} images`);
