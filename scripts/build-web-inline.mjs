// Builds a single, self-contained index.html of the web version (all JS, images and fonts inlined),
// so the prototype can be hosted anywhere (any path, any static host) and opened on a phone.
//
//   npm run build:web-inline   ->  dist-inline/index.html
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const webAssets = path.join(root, 'src/theme/assets.web.ts');
const mime = { '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.ttf': 'font/ttf' };
const dataUri = (file) => `data:${mime[path.extname(file)]};base64,${fs.readFileSync(file).toString('base64')}`;

// 1. Generate a web-only asset module that uses data URIs instead of bundler asset URLs.
const src = fs.readFileSync(path.join(root, 'src/theme/assets.ts'), 'utf8');
const resolveReq = (spec) =>
  spec.startsWith('.') ? path.resolve(root, 'src/theme', spec) : path.join(root, 'node_modules', spec);
let out = src.replace(/require\('([^']+)'\)/g, (_, spec) => {
  const uri = dataUri(resolveReq(spec));
  return spec.endsWith('.ttf') ? JSON.stringify(uri) : `{ uri: ${JSON.stringify(uri)} }`;
});
out = '// AUTO-GENERATED by scripts/build-web-inline.mjs. Do not edit or commit.\n' + out;
fs.writeFileSync(webAssets, out);

try {
  // 2. Export the web build.
  execSync('npx expo export --platform web --output-dir dist --clear', { cwd: root, stdio: 'inherit' });

  // 3. Inline the JS bundle(s) and favicon into index.html.
  const dist = path.join(root, 'dist');
  let html = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
  html = html.replace(/<script src="([^"]+)"([^>]*)><\/script>/g, (_, src, attrs) => {
    const js = fs.readFileSync(path.join(dist, src.replace(/^\//, '')), 'utf8').replace(/<\/script/g, '<\\/script');
    return `<script${attrs.replace(/\s*defer/, '')}>${js}</script>`;
  });
  html = html.replace(/<link rel="icon" href="([^"]+)"[^>]*>/, (_, href) => {
    const f = path.join(dist, href.replace(/^\//, ''));
    return fs.existsSync(f) ? `<link rel="icon" href="${dataUri(f)}">` : '';
  });
  // Scripts must run after <div id="root"> exists once `defer` is gone: move them to the end of <body>.
  const scripts = [];
  html = html.replace(/<script>[\s\S]*?<\/script>|<script [^>]*>[\s\S]*?<\/script>/g, (m) => {
    if (m.includes('__d(') || m.length > 50000) {
      scripts.push(m);
      return '';
    }
    return m;
  });
  html = html.replace('</body>', () => scripts.join('\n') + '</body>');
  fs.mkdirSync(path.join(root, 'dist-inline'), { recursive: true });
  fs.writeFileSync(path.join(root, 'dist-inline/index.html'), html);
  console.log(`dist-inline/index.html  ${(html.length / 1024 / 1024).toFixed(2)} MB`);
} finally {
  fs.rmSync(webAssets, { force: true });
}
